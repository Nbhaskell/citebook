"""Generate the seed files and knowledge-base documents from the universe.

Run from the repository root: python -m tools.build_data

Inputs: universe/facts.json (copied unchanged from Citedesk) and universe/citebook_extension.json.
Outputs (committed, and checked by tests/test_build_data.py):
  db/seed/services.json, technicians.json, customers.json, price_book.json, settings.json
  kb/docs/*.md: the universe documents plus online-booking.md, the policies only Citebook has.
Fix the generator or the inputs, never the generated files.
"""

from __future__ import annotations

import hashlib
import json
import uuid
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
UNIVERSE = ROOT / "universe"
SEED_DIR = ROOT / "db" / "seed"
KB_DOCS = ROOT / "kb" / "docs"


def load_facts() -> dict[str, Any]:
    data: dict[str, Any] = json.loads((UNIVERSE / "facts.json").read_text(encoding="utf-8"))
    return data


def load_extension() -> dict[str, Any]:
    data: dict[str, Any] = json.loads(
        (UNIVERSE / "citebook_extension.json").read_text(encoding="utf-8")
    )
    return data


def without_comments(mapping: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in mapping.items() if not k.startswith("_")}


def stable_uuid(kind: str, key: str) -> str:
    """A UUIDv4-shaped id that is the same on every run, so seeds are deterministic."""
    digest = hashlib.sha256(f"citebook:{kind}:{key}".encode()).digest()
    return str(uuid.UUID(bytes=digest[:16], version=4))


def _minor(dollars: int) -> int:
    return dollars * 100


def _money(minor: int) -> str:
    return f"${minor // 100:,}" if minor % 100 == 0 else f"${minor / 100:,.2f}"


def build_price_book(facts: dict[str, Any]) -> dict[str, Any]:
    pricing = facts["pricing"]
    facts_hash = hashlib.sha256((UNIVERSE / "facts.json").read_bytes()).hexdigest()
    return {
        "_comment": "SYNTHETIC. Generated by tools/build_data.py from universe/facts.json.",
        "version": f"facts-{facts_hash[:8]}",
        "call_out_fee_minor": _minor(pricing["call_out_fee"]["price"]),
        "call_out_credited_when_work_approved": True,
        "emergency_call_out_fee_minor": _minor(pricing["emergency_call_out_fee"]["price"]),
        "labour_per_hour_minor": _minor(pricing["labour"]["price_per_hour"]),
        "labour_minimum_hours": "1",
        "labour_increment_minutes_after_first_hour": 30,
        "parts_sales_tax_rate": f"{pricing['parts']['parts_sales_tax_rate']:.2f}",
        "outer_travel_fee_minor": _minor(facts["service_area"]["outer"]["travel_fee"]),
        "written_estimate_required_over_minor": _minor(pricing["written_estimate_required_over"]),
        "late_change_fee_minor": _minor(facts["policies"]["reschedule_and_cancel"]["late_fee"]),
    }


def build_services(facts: dict[str, Any], ext: dict[str, Any]) -> list[dict[str, Any]]:
    jobs = {j["job"]: j for j in facts["pricing"]["flat_price_jobs"]}
    limit = _minor(facts["pricing"]["written_estimate_required_over"])
    labour = _minor(facts["pricing"]["labour"]["price_per_hour"])
    rows = []
    for s in ext["services"]:
        kind = s["pricing_kind"]
        price = _minor(jobs[s["facts_job"]]["price"]) if "facts_job" in s else None
        if kind == "quote_only":
            bookable = 0
        elif kind == "hourly":
            bookable = int(labour * int(s["min_hours"]) <= limit)
        else:
            assert price is not None
            bookable = int(price <= limit)
        rows.append(
            {
                "code": s["code"],
                "name": s["name"],
                "description": s["description"],
                "skill": s["skill"],
                "windows_needed": s["windows_needed"],
                "pricing_kind": kind,
                "price_minor": price,
                "min_hours": s.get("min_hours"),
                "bookable_online": bookable,
                "first_step_code": s.get("first_step_code"),
                "active": 1,
            }
        )
    return rows


def build_technicians(ext: dict[str, Any]) -> list[dict[str, Any]]:
    return [
        {
            "id": stable_uuid("technician", t["key"]),
            "key": t["key"],
            "name": t["name"],
            "skills": t["skills"],
            "active": 1,
        }
        for t in ext["technicians"]
    ]


def build_customers(ext: dict[str, Any]) -> list[dict[str, Any]]:
    return [{"id": stable_uuid("customer", c["key"]), **c} for c in ext["customers"]]


def build_safety(facts: dict[str, Any]) -> dict[str, Any]:
    """The only safety advice the assistant may give, and the emergency line (D-052)."""
    return {
        "emergency_phone": facts["business"]["emergency_phone"],
        "instructions": without_comments(facts["safety_instructions"]),
    }


def build_settings(facts: dict[str, Any], ext: dict[str, Any]) -> dict[str, Any]:
    policies = without_comments(ext["citebook_policies"])
    hours = facts["hours"]
    return {
        "business_tz": ext["business_tz"],
        "office_hours": hours["office"],
        "visit_hours": without_comments(ext["visit_windows"]),
        "closed_dates": [d["date"] for d in hours["closed_dates"]],
        "arrival_window_minutes": hours["scheduled_visits"]["arrival_windows_hours"] * 60,
        "hold_ttl_business_hours": policies["hold_ttl_business_hours"],
        "staff_confirm_typical_business_hours": policies["staff_confirm_typical_business_hours"],
        "quote_ttl_minutes": policies["quote_ttl_minutes"],
        "free_cancel_hours": facts["policies"]["reschedule_and_cancel"]["free_with_notice_hours"],
        "max_reschedules": policies["max_reschedules"],
        "zip_areas": without_comments(ext["zip_areas"]),
        "verification_max_attempts": policies["verification_max_attempts"],
        "conversation_idle_minutes": policies["conversation_idle_minutes"],
        "synthetic_data": True,
    }


def build_online_booking_doc(
    facts: dict[str, Any], settings: dict[str, Any], book: dict[str, Any]
) -> str:
    """The policies only Citebook has, in the same plain style as the universe documents."""
    zips = settings["zip_areas"]

    def zip_list(zone: str) -> str:
        items = [f"{area['area']} ({code})" for code, area in zips.items() if area["zone"] == zone]
        return ", ".join(items)

    name = facts["business"]["name"]
    limit = _money(book["written_estimate_required_over_minor"])
    return f"""# Booking online

## How online booking works

You can ask for a visit in the chat on our website. The assistant checks open arrival windows, gives you a price from our price list and shows you a card with the details. Nothing is booked until you press Confirm on that card. Typing "yes" does not book anything.

## Held bookings

When you confirm, your booking is held, not confirmed. A staff member confirms it, usually within {settings["staff_confirm_typical_business_hours"]} business hours. A hold lasts {settings["hold_ttl_business_hours"]} business hours. Business hours are our office hours; time when the office is closed does not count. If no one confirms the hold in time, it ends and the time is offered to other customers.

## Prices in the chat

Every price in the chat comes from our price list. A price shown in the chat is valid for {settings["quote_ttl_minutes"]} minutes. The call-out fee is {_money(book["call_out_fee_minor"])} and is credited toward the work if you approve the work during the same visit. Labour is {_money(book["labour_per_hour_minor"])} per hour. In Dunmore Flats and Saltmarsh a travel fee of {_money(book["outer_travel_fee_minor"])} applies.

## Jobs you cannot book online

Jobs over {limit} need a written estimate before work starts, so a staff member arranges them. Jobs priced by quote are also arranged by a staff member. For sewer line repair, you can book a camera inspection online first. For slab leak or leak repair, you can book leak detection online first.

## ZIP codes we serve

Neighbourhoods we serve: {zip_list("core")}. Outer areas, with a travel fee: {zip_list("outer")}. We do not serve other ZIP codes.

## Changing or cancelling a booking

To change or cancel a booking in the chat, give the booking reference (it starts with CB-) and the last 4 digits of the phone number on the booking. After {settings["verification_max_attempts"]} attempts that do not match, a staff member helps instead. You can change or cancel free of charge with at least {settings["free_cancel_hours"]} hours' notice. With less notice, a staff member reviews the change and the fee of {_money(book["late_change_fee_minor"])}. A booking can be moved at most {settings["max_reschedules"]} times in the chat. Refunds are always reviewed by a person; the chat cannot give one.

## Talking to a person

You can ask for a person at any time. For an emergency, call {facts["business"]["emergency_phone"]}.

{name} is an invented business. This document is synthetic test data.
"""


def _dump(data: object) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def build_all() -> dict[Path, str]:
    facts, ext = load_facts(), load_extension()
    book = build_price_book(facts)
    settings = build_settings(facts, ext)
    out: dict[Path, str] = {
        SEED_DIR / "price_book.json": _dump(book),
        SEED_DIR / "settings.json": _dump(settings),
        SEED_DIR / "services.json": _dump(build_services(facts, ext)),
        SEED_DIR / "technicians.json": _dump(build_technicians(ext)),
        SEED_DIR / "customers.json": _dump(build_customers(ext)),
        SEED_DIR / "safety.json": _dump(build_safety(facts)),
        KB_DOCS / "online-booking.md": build_online_booking_doc(facts, settings, book),
    }
    for doc in sorted((UNIVERSE / "docs").glob("*.md")):
        out[KB_DOCS / doc.name] = doc.read_text(encoding="utf-8")
    return out


def main() -> None:
    for path, text in build_all().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
